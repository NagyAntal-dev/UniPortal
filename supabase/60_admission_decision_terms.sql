--      (security_invoker = on), az anon szerepkör pedig semmit nem olvashat
--      belőle. A 37-es migráció a nézetet e beállítás nélkül építette újra, így a
--      nézet a tulajdonos jogán futott, és az RLS nem érvényesült rajta. MÉRVE
--      élesben (2026-09-15): az oldal forrásában látható anon kulccsal a 35
--      felvételi folyamatból 35 volt lekérdezhető, bejelentkezés nélkül.
--   2) ref_no — ember által olvasható, egyedi folyamat-azonosító (a felületen
--      „FV-00042”). A meglévő sorok a létrehozásuk sorrendjében kapnak számot.
--   3) programs.intakes — melyik félévben indul a képzés: 'autumn' (őszi) és/vagy
--      'spring' (tavaszi). Alapból mindkettő, hogy a migráció semmit ne zárjon le.
--   4) admission_decide() — felvételi döntés: a jelentkező által megjelölt
--      képzések közül melyikre vettük fel, vagy elutasítás. A data.decision-be ír.
--   5) A data.decision kulcsot a jelentkező nem írhatja: a hallgatói felület a
--      teljes data mezőt visszamenti, és egy régi példány eltüntetné a döntést
--      (vagy egy rosszindulatú kérés hamisítana egyet).
--
-- A több képzésre szóló jelentkezés és a félév a data mezőben él
-- (data.program_ids, data.term): ehhez nem kell oszlop, a felület a migráció
-- előtt is tudja menteni. Idempotens, többször is lefuttatható.
